#!/usr/bin/env python3
"""Generate the dependency maps from the skills. Never edit a map by hand.

  gen-maps.py           write plugins/<p>/.brain/MAP.md and ./MAP.md
  gen-maps.py --check   exit 1 if any map on disk differs from what the skills produce
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from processlib import load_process

ROOT = pathlib.Path(__file__).resolve().parent.parent
EDGE = re.compile(r"^- \*\*(Requires|Optional \(ordered\)|Optional \(enriching\)):\*\*\s*(.*)$")
KINDS = {"Requires": "requires", "Optional (ordered)": "optional-ordered",
         "Optional (enriching)": "optional-enriching"}
ORDERING = ("requires", "optional-ordered")


def description(text):
    m = re.search(r"^description:\s*(.*?)(?=^\S)", text, re.M | re.S)
    flat = " ".join(m.group(1).replace(">-", "").split()) if m else ""
    return re.split(r"(?<=\.)\s", flat, maxsplit=1)[0]


def load_skill(path):
    text = path.read_text(encoding="utf-8")
    body = re.search(r"^## Depends on\n(.*?)(?=^## )", text, re.M | re.S)
    body = body.group(1) if body else ""
    skill = {"name": path.parent.name, "desc": description(text), "edges": [],
             "produces": [], "specializes": None}
    for line in body.splitlines():
        e = EDGE.match(line)
        if e:
            t = re.match(r"`([^`]+)`(?:\s*\(`([^`]+)`\))?", e.group(2))
            if t and t.group(1) != "none":
                skill["edges"].append((KINDS[e.group(1)], t.group(1), t.group(2) or ""))
        elif line.startswith("- **Produces:**"):
            skill["produces"] = re.findall(r"`([^`]+)`(?=:)", line)
        else:
            s = re.match(r"^- \*\*Specializes:\*\*\s*`([^`]+)`", line)
            if s:
                skill["specializes"] = s.group(1)
    skill["edges"].sort()
    return skill


def load_all():
    plugins = {}
    for pj in sorted(ROOT.glob("plugins/*/.claude-plugin/plugin.json")):
        pdir = pj.parent.parent
        plugins[pdir.name] = [load_skill(p) for p in sorted(pdir.glob("skills/*/SKILL.md"))]
    return plugins


def layers(owner, skills):
    """Longest-path depth over ordering edges. Returns (depth by skill, cycle members)."""
    deps = {n: {t for k, t, _ in s["edges"] if k in ORDERING and t in owner}
            for n, s in skills.items()}
    depth, state = {}, {}

    def visit(n):
        if n in depth:
            return depth[n]
        if state.get(n) == 1:
            raise RecursionError(n)
        state[n] = 1
        depth[n] = 1 + max((visit(d) for d in deps[n]), default=-1)
        state[n] = 2
        return depth[n]

    try:
        for n in sorted(deps):
            visit(n)
    except RecursionError as e:
        return None, str(e)
    return depth, None


def cell(items):
    return ", ".join(f"`{i}`" for i in items) if items else "none"


def edge_cell(skill, kind):
    return cell([t for k, t, _ in skill["edges"] if k == kind])


def plugin_map(plugin, skills, owner):
    out = [f"# {plugin}: map", "",
           "Generated by `scripts/gen-maps.py` from the skills. Do not edit.", "",
           "| Skill | Specializes | Requires | Ordered | Enriching | Produces |", "|---|---|---|---|---|---|"]
    for s in skills:
        out.append(f"| `{s['name']}` | {cell([s['specializes']] if s['specializes'] else [])} | "
                   f"{edge_cell(s, 'requires')} | {edge_cell(s, 'optional-ordered')} | "
                   f"{edge_cell(s, 'optional-enriching')} | {cell(s['produces'])} |")
    out += ["", "## Purpose", ""]
    out += [f"- `{s['name']}`: {s['desc']}" for s in skills]
    procs = [load_process(ROOT / "plugins" / plugin, f)
             for f in sorted((ROOT / "plugins" / plugin).glob("processes/*.md"))]
    if procs:
        out += ["", "## Processes", ""]
        out += [f"- `{q['id']}`: {q['title']} (roles: {cell(q['roles'])}; sources: {', '.join(q['sources'])})" for q in procs]
    ext = sorted({(owner[t], t) for s in skills for k, t, _ in s["edges"]
                  if k in ORDERING and t in owner and owner[t] != plugin})
    out += ["", "## Needs from other plugins (ordering edges only)", ""]
    out += [f"- `{p}` via `{t}`" for p, t in ext] or ["- none"]
    return "\n".join(out) + "\n"


def root_map(plugins, owner, by_name):
    depth, cyc = layers(owner, by_name)
    if depth is None:
        sys.exit(f"ordering cycle through '{cyc}'")
    out = ["# Map", "",
           "Generated by `scripts/gen-maps.py` from the skills. Do not edit.", "",
           "Root of the brain import. Read this first, then each plugin's `.brain/MAP.md`.", "",
           "## How to import", "",
           "- Dry-run a plugin: `python scripts/import-brain.py <plugin>`. It lists what would enter.",
           "- Apply after the owner approves: `--apply`, optionally `--only <id>...`.",
           "- Import in layer order below, so every skill arrives after what it requires.",
           "- Per-plugin detail (edges, products, purpose): `plugins/<plugin>/.brain/MAP.md`.",
           "- Manifest, rules and skill files: `plugins/<plugin>/.brain/`.", "",
           "## Plugins", "", "| Plugin | Skills | Produces |", "|---|---|---|"]
    for p, skills in plugins.items():
        prod = sorted({a for s in skills for a in s["produces"]})
        out.append(f"| `{p}` | {len(skills)} | {cell(prod)} |")
    out += ["", "## Layers (execution order from Requires and Optional-ordered edges)", ""]
    for d in range(max(depth.values(), default=-1) + 1):
        names = sorted(n for n, v in depth.items() if v == d)
        out.append(f"{d}. {', '.join(f'`{n}`' for n in names)}")
    out += ["", "## Edges across plugins", "", "| From | Edge | To | Artifact |", "|---|---|---|---|"]
    rows = sorted((owner[s["name"]], s["name"], k, t, a) for skills in plugins.values()
                  for s in skills for k, t, a in s["edges"]
                  if t in owner and owner[t] != owner[s["name"]])
    out += [f"| `{p}/{n}` | {k} | `{owner[t]}/{t}` | {cell([a] if a else [])} |"
            for p, n, k, t, a in rows]
    return "\n".join(out) + "\n"


def main():
    plugins = load_all()
    owner = {s["name"]: p for p, ss in plugins.items() for s in ss}
    by_name = {s["name"]: s for ss in plugins.values() for s in ss}
    files = {ROOT / "MAP.md": root_map(plugins, owner, by_name)}
    for p, skills in plugins.items():
        files[ROOT / "plugins" / p / ".brain" / "MAP.md"] = plugin_map(p, skills, owner)
    stale = [f for f, c in files.items() if not f.is_file() or f.read_text(encoding="utf-8") != c]
    if "--check" in sys.argv:
        for f in stale:
            print(f"stale map: {f.relative_to(ROOT).as_posix()} (run scripts/gen-maps.py)")
        sys.exit(1 if stale else 0)
    for f, c in files.items():
        f.parent.mkdir(exist_ok=True)
        f.write_text(c, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} maps, {len(stale)} changed")


if __name__ == "__main__":
    main()
